package atropos.core.factory

import atropos.core.security.RedactionFilter
import java.util.Locale

class RepoScaffold(
    private val redactionFilter: RedactionFilter = RedactionFilter(),
    private val behaviorTemplate: LanguageBehaviorTemplate = LanguageBehaviorTemplate(),
    private val authPlanner: AppAuthPlanner = AppAuthPlanner(),
    private val backendPlanner: AppBackendIntegrationPlanner = AppBackendIntegrationPlanner(),
    private val databasePlanner: AppDatabaseSecurityPlanner = AppDatabaseSecurityPlanner()
) {
    fun files(spec: AppProjectSpec, lineage: FactoryLineage? = null): LinkedHashMap<String, String> {
        val packageName = AppProjectGenerator.safeName(spec.intent.name)
        // The language the operator's own document names, not Kotlin by
        // assumption. A scaffold is a claim about where code goes, and making
        // that claim in the wrong ecosystem files every subsequently generated
        // file under it -- beside a verify.sh that cannot run any of them.
        val projectLayout = ProjectLayout.resolve(spec)
        val detection = projectLayout.detection
        val language = projectLayout.language
        val title = spec.intent.name.replaceFirstChar { it.titlecase(Locale.US) }
        val featureText = redactionFilter.redact(spec.intent.features.joinToString(", ")).ifBlank { "general application" }
        val safePrompt = redactionFilter.redact(spec.prompt)
        val lineageText = lineage?.let {
            "Lineage:\n- prompt_sha256: ${it.promptSha256}\n- prompt_fingerprint: ${it.promptFingerprint}\n- prompt_spans: ${it.promptSpans}\n- research_sha256: ${it.researchSha256}\n"
        }.orEmpty()
        // A language this cannot lay out gets a generic tree and a verify.sh
        // that refuses honestly, not a JVM tree that pretends. The operator
        // finds out now, rather than after the providers have filled the wrong
        // directories with correct code.
        val layout = projectLayout.scaffold
        // `//` at the top of a Python file is a syntax error, so the
        // provenance header would have broken the very file it documented.
        val mark = layout.commentPrefix
        val sourceLineage = lineage?.let {
            "$mark ATROPOS lineage: project_id=${it.projectId}\n" +
                "$mark prompt_sha256=${it.promptSha256}\n" +
                "$mark prompt_fingerprint=${it.promptFingerprint}\n" +
                "$mark prompt_spans=${it.promptSpans}\n" +
                "$mark research_sha256=${it.researchSha256}\n"
        }.orEmpty()
        val authPlan = authPlanner.planAuthenticationFlow(spec.intent.kind)
        val plannedFeatures = atropos.core.integration.DependencyDeduplicator.deduplicate(
            spec.intent.features.ifEmpty { listOf(spec.intent.name) }
        )
        val endpointPlan = backendPlanner.planApiEndpoints(plannedFeatures)
        val schemaPlan = databasePlanner.planSchema(spec.intent.name)
        val map = linkedMapOf<String, String>()
        // A generic layout declares no source or test path. Writing an empty
        // key would put a file at the repository root with no name.
        // Every file the document said the project has.
        //
        // A build specification states its layout as a directory listing, and
        // the factory used to lay out whatever its own scaffold decided
        // instead -- so a document naming two hundred files produced eleven of
        // someone else's, and every file a provider wrote afterwards landed in
        // a tree the specification never described. Written first, so the
        // seed program and the standard repository files below overwrite their
        // own entries rather than being overwritten by an empty seed.
        projectLayout.declared
            .filterNot { it.isDirectory }
            .forEach { entry -> map[entry.path] = DeclaredFileSeed.contentFor(entry) }
        // A declared directory with no files in it still has to exist.
        projectLayout.declared
            .filter { it.isDirectory }
            .filterNot { directory ->
                projectLayout.declared.any { !it.isDirectory && it.path.startsWith(directory.path + "/") }
            }
            .forEach { directory -> map["${directory.path}/.gitkeep"] = "" }

        if (layout.sourcePath.isNotBlank()) {
            val program = behaviorTemplate.render(projectLayout, spec, packageName)
            map[layout.sourcePath] = layout.withLineage(program.source, sourceLineage)
            map[layout.testPath] = layout.withLineage(program.test, sourceLineage)
            // Whatever else the language needs beside those two: a Python
            // `__main__.py`, a C++ header, a Swift executable target. Not
            // lineage-marked -- they carry no generated behaviour to trace.
            program.extraSources.forEach { (path, contents) -> map[path] = contents }
        }
        map["README.md"] = "# $title\n\nGenerated by ATROPOS from: $safePrompt\n\nKind: ${spec.intent.kind}\nFeatures: $featureText\n\n## Planned boundaries\n- $authPlan\n- ${endpointPlan.joinToString("; ")}\n- $schemaPlan\n\n$lineageText"
        map["LICENSE"] = "MIT License\n\nCopyright (c) ATROPOS\n"
        map[".gitignore"] = layout.ignore
        map["AGENTS.md"] = "# $title Repository\n\n- Owner: the repository operator.\n- Territory: generated source and evidence remain inside this repository.\n- Verification: run `./verify.sh` before promoting changes.\n- Evidence: `.atropos/evidence/app-manifest.txt` records the source-tree digest and commit.\n- Secrets: never commit credentials; redact operator prompts before persistence.\n\n$lineageText"
        map["verify.sh"] = layout.verify

        // The manifest the ecosystem expects -- pyproject.toml, package.json,
        // go.mod, Cargo.toml. Without one, a generated repository is a pile of
        // source files that no tool in its own language will install or run.
        layout.manifests.forEach { (path, contents) -> map[path] = contents }

        // Said in the README, because a repository that cannot verify itself
        // must explain why in the first file anyone opens.
        map["README.md"] = map.getValue("README.md") + when (detection) {
            is ProjectLanguage.Detection.Scaffolded ->
                "\nLanguage: ${detection.language.displayName}\n"
            is ProjectLanguage.Detection.Unsupported ->
                "\nLanguage: ${detection.displayName}\n\n" +
                    "ATROPOS has no scaffold for ${detection.displayName}, so this repository has " +
                    "no source layout, no manifest and no working `verify.sh`. Generated code is " +
                    "still written and verified through the DAG; the project structure is yours " +
                    "to lay out.\n"
            ProjectLanguage.Detection.Unstated ->
                "\nLanguage: ${language.displayName} (nothing else was stated)\n"
        }

        // Kotlin serves static assets from resources; every other ecosystem
        // uses a top-level `static/`. Writing JVM resource paths into a Python
        // project puts the frontend somewhere nothing will serve it from.
        val staticRoot =
            if (language == ProjectLanguage.KOTLIN &&
                detection !is ProjectLanguage.Detection.Unsupported
            ) "src/main/resources/static/" else "static/"

        if (spec.intent.kind.lowercase() == "web") {
            map[staticRoot + "index.html"] = """
                <!DOCTYPE html>
                <html lang="en">
                <head>
                    <meta charset="UTF-8">
                    <title>$title</title>
                    <link rel="stylesheet" href="style.css">
                </head>
                <body>
                    <nav class="navbar">
                        <div class="logo">$title</div>
                        <ul class="nav-links">
                            <li><a href="#home">Home</a></li>
                            <li><a href="#features">Features</a></li>
                            <li><a href="#about">About</a></li>
                        </ul>
                    </nav>
                    <main class="content">
                        <h1>Welcome to $title</h1>
                        <form id="action-form">
                            <label for="input-field">Submit feedback:</label>
                            <input type="text" id="input-field" name="feedback" required>
                            <button type="submit">Submit</button>
                        </form>
                    </main>
                    <script src="app.js"></script>
                </body>
                </html>
            """.trimIndent()

            map[staticRoot + "style.css"] = """
                /* Design System Colors */
                :root {
                    --primary-color: #0066cc;
                    --background-color: #f5f5f7;
                    --text-color: #1d1d1f;
                }
                body {
                    font-family: sans-serif;
                    background-color: var(--background-color);
                    color: var(--text-color);
                }
                .navbar {
                    display: flex;
                    justify-content: space-between;
                }
                .logo {
                    color: var(--primary-color);
                }
            """.trimIndent()

            map[staticRoot + "app.js"] = """
                console.log('App initialized');
                document.getElementById('action-form')?.addEventListener('submit', (e) => {
                    e.preventDefault();
                    alert('Submitted successfully');
                });
            """.trimIndent()
        }

        return map
    }
}
