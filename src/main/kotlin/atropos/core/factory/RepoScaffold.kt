package atropos.core.factory

import atropos.core.security.RedactionFilter
import java.util.Locale

/**
 * RepoScaffold rewritten for zero-template architecture.
 *
 * Provides only non-code repository infrastructure: README, LICENSE,
 * .gitignore, verify.sh, and ecosystem manifests.
 *
 * All source and test code synthesis is delegated to ContractLatticeSynthesizer.
 * Zero references to AppSourceTemplate or LanguageScaffold remain.
 */
class RepoScaffold(
    private val redactionFilter: RedactionFilter = RedactionFilter(),
    private val authPlanner: AppAuthPlanner = AppAuthPlanner(),
    private val backendPlanner: AppBackendIntegrationPlanner = AppBackendIntegrationPlanner(),
    private val databasePlanner: AppDatabaseSecurityPlanner = AppDatabaseSecurityPlanner()
) {
    fun files(spec: AppProjectSpec, lineage: FactoryLineage? = null): LinkedHashMap<String, String> {
        val packageName = AppProjectGenerator.safeName(spec.intent.name)
        val detection = ProjectLanguage.detect(spec.prompt)
        val language = ProjectLanguage.layoutFor(detection)
        val title = spec.intent.name.replaceFirstChar { it.titlecase(Locale.US) }
        val featureText = redactionFilter.redact(spec.intent.features.joinToString(", ")).ifBlank { "general application" }
        val safePrompt = redactionFilter.redact(spec.prompt)
        val lineageText = lineage?.let {
            "Lineage:\n- prompt_sha256: ${it.promptSha256}\n- prompt_fingerprint: ${it.promptFingerprint}\n- prompt_spans: ${it.promptSpans}\n- research_sha256: ${it.researchSha256}\n"
        }.orEmpty()

        val layout = ProjectLanguageLayout.forLanguage(language)
        val mark = layout.commentPrefix
        val sourceLineage = lineage?.let {
            "$mark ATROPOS lineage: project_id=${it.projectId}\n" +
                "$mark prompt_sha256=${it.promptSha256}\n" +
                "$mark prompt_fingerprint=${it.promptFingerprint}\n" +
                "$mark prompt_spans=${it.promptSpans}\n" +
                "$mark research_sha256=${it.researchSha256}\n"
        }.orEmpty()

        val authPlan = authPlanner.planAuthenticationFlow(spec.intent.kind)
        val plannedFeatures = atropos.core.integration.DependencyDeduplicator.deduplicate(
            spec.intent.features.ifEmpty { listOf(spec.intent.name) }
        )
        val endpointPlan = backendPlanner.planApiEndpoints(plannedFeatures)
        val schemaPlan = databasePlanner.planSchema(spec.intent.name)

        val map = linkedMapOf<String, String>()

        // README.md
        map["README.md"] = "# $title\n\nGenerated by ATROPOS from: $safePrompt\n\nKind: ${spec.intent.kind}\nFeatures: $featureText\n\n## Planned boundaries\n- $authPlan\n- ${endpointPlan.joinToString("; ")}\n- $schemaPlan\n\n$lineageText"

        // LICENSE
        map["LICENSE"] = "MIT License\n\nCopyright (c) ATROPOS\n"

        // .gitignore
        map[".gitignore"] = layout.ignore

        // AGENTS.md
        map["AGENTS.md"] = """# $title Repository

- Owner: the repository operator.
- Territory: generated source and evidence remain inside this repository.
- Verification: run `./verify.sh` before promoting changes.
- Evidence: `.atropos/evidence/app-manifest.txt` records the source-tree digest and commit.
- Secrets: never commit credentials; redact operator prompts before persistence.

$lineageText""".trimIndent()

        // verify.sh
        map["verify.sh"] = layout.verify

        // Ecosystem manifests
        layout.manifests.forEach { (path, contents) -> map[path] = contents }

        // Language note in README
        map["README.md"] = map.getValue("README.md") + when (detection) {
            is ProjectLanguage.Detection.Scaffolded ->
                "\nLanguage: ${detection.language.displayName}\n"
            is ProjectLanguage.Detection.Unsupported ->
                "\nLanguage: ${detection.displayName}\n\n" +
                    "ATROPOS has no scaffold for ${detection.displayName}, so this repository has " +
                    "no source layout, no manifest and no working `verify.sh`. Generated code is " +
                    "still written and verified through the DAG; the project structure is yours " +
                    "to lay out.\n"
            ProjectLanguage.Detection.Unstated ->
                "\nLanguage: ${language.displayName} (nothing else was stated)\n"
        }

        // Static assets for web projects
        val staticRoot = if (language == ProjectLanguage.KOTLIN &&
            detection !is ProjectLanguage.Detection.Unsupported
        ) "src/main/resources/static/" else "static/"

        if (spec.intent.kind.lowercase() == "web") {
            map[staticRoot + "index.html"] = """
                <!DOCTYPE html>
                <html lang="en">
                <head>
                    <meta charset="UTF-8">
                    <title>$title</title>
                    <link rel="stylesheet" href="style.css">
                </head>
                <body>
                    <nav class="navbar">
                        <div class="logo">$title</div>
                        <ul class="nav-links">
                            <li><a href="#home">Home</a></li>
                            <li><a href="#features">Features</a></li>
                            <li><a href="#about">About</a></li>
                        </ul>
                    </nav>
                    <main class="content">
                        <h1>Welcome to $title</h1>
                        <form id="action-form">
                            <label for="input-field">Submit feedback:</label>
                            <input type="text" id="input-field" name="feedback" required>
                            <button type="submit">Submit</button>
                        </form>
                    </main>
                    <script src="app.js"></script>
                </body>
                </html>
            """.trimIndent()

            map[staticRoot + "style.css"] = """
                /* Design System Colors */
                :root {
                    --primary-color: #0066cc;
                    --background-color: #f5f5f7;
                    --text-color: #1d1d1f;
                }
                body {
                    font-family: sans-serif;
                    background-color: var(--background-color);
                    color: var(--text-color);
                }
                .navbar {
                    display: flex;
                    justify-content: space-between;
                }
                .logo {
                    color: var(--primary-color);
                }
            """.trimIndent()

            map[staticRoot + "app.js"] = """
                console.log('App initialized');
                document.getElementById('action-form')?.addEventListener('submit', (e) => {
                    e.preventDefault();
                    alert('Submitted successfully');
                });
            """.trimIndent()
        }

        return map
    }
}

/**
 * Minimal language layout data — replaces LanguageScaffold with only the
 * structural metadata needed for repository infrastructure (not source code).
 */
data class ProjectLanguageLayout(
    val language: ProjectLanguage,
    val sourcePathPrefix: String,
    val testPathPrefix: String,
    val manifests: Map<String, String>,
    val verify: String,
    val ignore: String,
    val commentPrefix: String
) {
    companion object {
        fun forLanguage(language: ProjectLanguage): ProjectLanguageLayout = when (language) {
            ProjectLanguage.KOTLIN -> ProjectLanguageLayout(
                language = ProjectLanguage.KOTLIN,
                sourcePathPrefix = "kotlin",
                testPathPrefix = "kotlin",
                manifests = emptyMap(),
                verify = "#!/usr/bin/env sh\nset -eu\nmain=src/main/kotlin/\${PACKAGE}/Main.kt\n" +
                    "test=src/test/kotlin/\${PACKAGE}/MainTest.kt\n" +
                    "command -v kotlinc >/dev/null 2>&1 || " +
                    "{ printf '%s\\n' 'kotlinc is required for generated-test verification' >&2; exit 1; }\n" +
                    "mkdir -p build\nkotlinc \"\$main\" \"\$test\" -include-runtime -d build/app-tests.jar\n" +
                    "java -cp build/app-tests.jar \${PACKAGE}.MainTestKt\n" +
                    "printf '%s\\n' APP_FACTORY_VERIFY_OK\n",
                ignore = "build/\n.gradle/\n.idea/\n",
                commentPrefix = "//"
            )
            ProjectLanguage.JAVA -> ProjectLanguageLayout(
                language = ProjectLanguage.JAVA,
                sourcePathPrefix = "java",
                testPathPrefix = "java",
                manifests = mapOf(
                    "pom.xml" to "<project>\n  <modelVersion>4.0.0</modelVersion>\n" +
                        "  <groupId>\${PACKAGE}</groupId>\n  <artifactId>\${PACKAGE}</artifactId>\n" +
                        "  <version>0.1.0</version>\n</project>\n"
                ),
                verify = "#!/usr/bin/env sh\nset -eu\ncommand -v javac >/dev/null 2>&1 || " +
                    "{ printf '%s\\n' 'javac is required' >&2; exit 1; }\nmkdir -p build\n" +
                    "javac -d build src/main/java/\${PACKAGE}/Main.java src/test/java/\${PACKAGE}/MainTest.java\n" +
                    "java -cp build \${PACKAGE}.MainTest\nprintf '%s\\n' APP_FACTORY_VERIFY_OK\n",
                ignore = "build/\ntarget/\n*.class\n",
                commentPrefix = "//"
            )
            ProjectLanguage.PYTHON -> ProjectLanguageLayout(
                language = ProjectLanguage.PYTHON,
                sourcePathPrefix = "",
                testPathPrefix = "tests",
                manifests = mapOf(
                    "pyproject.toml" to
                        "[project]\nname = \"\${PACKAGE}\"\nversion = \"0.1.0\"\nrequires-python = \">=3.11\"\n\n" +
                        "[build-system]\nrequires = [\"setuptools>=68\"]\nbuild-backend = \"setuptools.build_meta\"\n",
                    "requirements.txt" to "",
                    "requirements-dev.txt" to "pytest\n"
                ),
                verify = "#!/usr/bin/env sh\nset -eu\ncommand -v python3 >/dev/null 2>&1 || " +
                    "{ printf '%s\\n' 'python3 is required' >&2; exit 1; }\n" +
                    "python3 -m pytest tests -q\nprintf '%s\\n' APP_FACTORY_VERIFY_OK\n",
                ignore = "__pycache__/\n*.pyc\n.venv/\n.pytest_cache/\ndist/\n",
                commentPrefix = "#"
            )
            ProjectLanguage.TYPESCRIPT -> ProjectLanguageLayout(
                language = ProjectLanguage.TYPESCRIPT,
                sourcePathPrefix = "src",
                testPathPrefix = "src",
                manifests = mapOf(
                    "package.json" to
                        "{\n  \"name\": \"\${PACKAGE}\",\n  \"version\": \"0.1.0\",\n  \"type\": \"module\",\n" +
                        "  \"scripts\": { \"test\": \"node --test\" }\n}\n",
                    "tsconfig.json" to
                        "{\n  \"compilerOptions\": {\n    \"target\": \"ES2022\",\n    \"module\": \"ES2022\",\n" +
                        "    \"strict\": true,\n    \"outDir\": \"dist\"\n  },\n  \"include\": [\"src\"]\n}\n"
                ),
                verify = "#!/usr/bin/env sh\nset -eu\ncommand -v node >/dev/null 2>&1 || " +
                    "{ printf '%s\\n' 'node is required' >&2; exit 1; }\nnpm test\n" +
                    "printf '%s\\n' APP_FACTORY_VERIFY_OK\n",
                ignore = "node_modules/\ndist/\n*.log\n",
                commentPrefix = "//"
            )
            ProjectLanguage.GO -> ProjectLanguageLayout(
                language = ProjectLanguage.GO,
                sourcePathPrefix = ".",
                testPathPrefix = ".",
                manifests = mapOf("go.mod" to "module \${PACKAGE}\n\ngo 1.22\n"),
                verify = "#!/usr/bin/env sh\nset -eu\ncommand -v go >/dev/null 2>&1 || " +
                    "{ printf '%s\\n' 'go is required' >&2; exit 1; }\ngo test ./...\n" +
                    "printf '%s\\n' APP_FACTORY_VERIFY_OK\n",
                ignore = "bin/\n*.exe\n",
                commentPrefix = "//"
            )
            ProjectLanguage.RUST -> ProjectLanguageLayout(
                language = ProjectLanguage.RUST,
                sourcePathPrefix = "src",
                testPathPrefix = "tests",
                manifests = mapOf(
                    "Cargo.toml" to "[package]\nname = \"\${PACKAGE}\"\nversion = \"0.1.0\"\nedition = \"2021\"\n"
                ),
                verify = "#!/usr/bin/env sh\nset -eu\ncommand -v cargo >/dev/null 2>&1 || " +
                    "{ printf '%s\\n' 'cargo is required' >&2; exit 1; }\ncargo test\n" +
                    "printf '%s\\n' APP_FACTORY_VERIFY_OK\n",
                ignore = "target/\n",
                commentPrefix = "//"
            )
            else -> ProjectLanguageLayout(
                language = language,
                sourcePathPrefix = "",
                testPathPrefix = "",
                manifests = emptyMap(),
                verify = "#!/usr/bin/env sh\nset -eu\nprintf '%s\\n' 'ATROPOS has no scaffold for ${language.displayName}; " +
                    "add this project\\'s own build and test commands here.' >&2\nexit 1\n",
                ignore = "*.log\n",
                commentPrefix = "#"
            )
        }
    }
}