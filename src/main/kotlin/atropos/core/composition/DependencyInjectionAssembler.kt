package atropos.core.composition

import atropos.core.contract.ContractLattice
import java.nio.file.Files
import java.nio.file.Path

class DependencyInjectionAssembler {
    fun assemble(
        lattice: ContractLattice,
        implementations: Map<String, String>,
        worktree: Path
    ): Path {
        Files.createDirectories(worktree)
        val moduleBindings = mutableListOf<String>()

        for ((interfacePath, _) in lattice.interfaceFiles) {
            val interfaceName = interfacePath.substringAfterLast("/").substringBeforeLast(".kt")
            val implName = implementations.entries.firstOrNull { (_, content) ->
                content.contains(": $interfaceName") || content.contains("implements $interfaceName")
            }?.key?.substringAfterLast("/")?.substringBeforeLast(".kt") ?: "${interfaceName}Impl"

            moduleBindings.add("        single<$interfaceName> { $implName() }")
        }

        val assemblyContent = """/* SPDX-License-Identifier: AGPL-3.0-only */
package atropos.generated.di

import org.koin.dsl.module
import org.koin.core.module.Module

/**
 * Autogenerated Wave-3 Dependency Injection Assembly.
 * Monoidal composition (§3): binds Wave-0 contracts to verified implementations.
 * Direct cross-coupling across partitions is forbidden.
 */
object AppModule {
    val module: Module = module {
${moduleBindings.joinToString("\n")}
    }
}
"""
        val targetPath = worktree.resolve("src/main/kotlin/atropos/generated/di/AppModule.kt")
        Files.createDirectories(targetPath.parent)
        Files.writeString(targetPath, assemblyContent)
        return targetPath
    }
}
