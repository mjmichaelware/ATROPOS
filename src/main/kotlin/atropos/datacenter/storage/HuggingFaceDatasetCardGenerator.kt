package atropos.datacenter.storage

/**
 * HuggingFaceDatasetCardGenerator
 *
 * Generates canonical Hugging Face Dataset Card metadata (README.md)
 * with structured YAML frontmatter, split architectures, and 100 GB Parquet topology.
 */
class HuggingFaceDatasetCardGenerator {
    fun generateDatasetCard(
        datasetName: String = "atropos/telemetry-corpus",
        totalSizeGb: Long = 100L
    ): String {
        return """---
configs:
  - config_name: telemetry_traces
    data_files:
      - split: train
        path: "telemetry/traces/train-*.parquet"
      - split: validation
        path: "telemetry/traces/val-*.parquet"
      - split: test
        path: "telemetry/traces/test-*.parquet"
  - config_name: process_supervision
    data_files:
      - split: train
        path: "formal/smt_solvers/prm_train-*.parquet"
  - config_name: dpo_preferences
    data_files:
      - split: train
        path: "dopamine/rewards/dpo_pairs-*.parquet"
dataset_info:
  features:
    - name: trajectory_id
      dtype: string
    - name: messages
      list:
        - name: role
          dtype: string
        - name: content
          dtype: string
    - name: scalar_reward
      dtype: float32
    - name: prm_steps
      list:
        - name: step_index
          dtype: int32
        - name: prm_label
          dtype: float32
  splits:
    - name: train
      num_bytes: 85899345920
      num_examples: 12500000
    - name: validation
      num_bytes: 5368709120
      num_examples: 780000
    - name: test
      num_bytes: 5368709120
      num_examples: 780000
  download_size: 21474836480
  dataset_size: 96636764160
license: apache-2.0
task_categories:
  - reinforcement-learning
  - text-generation
task_ids:
  - process-reward-modeling
  - offline-rl
tags:
  - code-generation
  - neurosymbolic
  - active-inference
  - tree-search
size_categories:
  - 10M<n<100M
---

# $datasetName

## Dataset Description
High-density process-supervised telemetry corpus and neurodevelopmental reward dataset generated by ATROPOS.
Features:
- Total Storage Cap: $totalSizeGb GB (Zstandard Dictionary Compressed Parquet)
- Process-Supervised PRM steps annotated with Monte Carlo rollouts and formal SMT witnesses
- Strict separation of terminated and truncated MDP transitions
- Bounded, tanh-clamped pediatric dopamine reward signals with synaptic linkage graphs
"""
    }

    companion object {
        val defaultGenerator = HuggingFaceDatasetCardGenerator()
    }
}
