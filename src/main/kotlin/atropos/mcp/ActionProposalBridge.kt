package atropos.mcp

import org.json.JSONObject
import atropos.core.governance.ActionProposal
import atropos.core.governance.Phase20ProposalGate

class ActionProposalBridge(val gate: Phase20ProposalGate) {
    fun convertToolOutputToProposal(toolName: String, outputJson: String): ActionProposal {
        val json = try { JSONObject(outputJson) } catch (_: Exception) { JSONObject() }
        val targetPath = json.optString("path", "unassigned.txt")
        val diff = json.optString("diff", "")
        val rationale = json.optString("rationale", "Generated by MCP tool $toolName")

        return ActionProposal(
            proposalId = "mcp-prop-${System.currentTimeMillis()}",
            authorAgentId = "mcp:$toolName",
            rationale = rationale,
            targetPaths = listOf(targetPath),
            patchDiff = diff
        )
    }
}
